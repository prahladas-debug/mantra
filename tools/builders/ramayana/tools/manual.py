def structural(k, s, items, log):
    ref = f'{k}.{s}'
    # drop empty items
    items = [it for it in items if it[1].strip()]
    if (k, s) == (1, 31):
        # the base has verse 19 twice: a word-split copy whose first half is the missing third line of 18
        i = next(i for i, it in enumerate(items) if it[0] == 19)
        assert 'निवर्तयामास' in items[i][1]
        items[i - 1][1] += '\nनिवर्तयामास ततः सर्षिसङ्घः सपक्षिणः'
        del items[i]
        log.append((ref + '.18', 'structure', 'the base repeats 19 in word-split form; its first half is the third line of 18 (IITK 1.31.18, CE)', 'निवर्तयामास ततः सर्षिसङ्घः सपक्षिणः'))
    for it in items:
        it[1] = '\n'.join(l for l in it[1].split('\n') if not re.search(r'[A-Za-z]', l) and not re.match(r'^\s*[०-९0-9]', l))
    if (k, s) == (7, 8):
        # the base numbers the first half of verse 5 as a second '4'
        i = [j for j, it in enumerate(items) if it[0] == 4][1]
        items[i + 1][1] = items[i][1] + '\n' + items[i + 1][1]
        del items[i]
        log.append((ref + '.5', 'structure', 'the base numbers the first half of 5 as a second 4; joined to 5 as in IITK', ''))
    if (k, s) == (7, 51):
        import json, os
        w = json.load(open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'work/iitk.json')))['7']['51']
        t = dict(w)['7.51.14']
        i = next(j for j, it in enumerate(items) if it[0] == 14)
        items.insert(i, [14, '\n'.join(x.strip(' ।') for x in t.split('।') if x.strip())])
        log.append((ref + '.14', 'restored', 'missing in the base (its numbering skips 18 to resynchronise); taken from IITK 7.51.14', t))
    if (k, s) == (3, 56):
        i = next(i for i, it in enumerate(items) if 'प्रक्षिप्त' in it[1])
        PRAKSHIPTA[(k, s)] = i
    return items


