SIGN = {'अ': '', 'आ': 'ा', 'इ': 'ि', 'ई': 'ी', 'उ': 'ु', 'ऊ': 'ू', 'ऋ': 'ृ', 'ए': 'े', 'ऐ': 'ै', 'ओ': 'ो', 'औ': 'ौ'}


def join_split(h):
    """Sandhi for a word-split half-line of the valmikiramayan.net kind (used to merge with IITK; logged)."""
    t = re.sub(r'\s+', ' ', h).strip()
    # transliteration artifacts of that source
    t = re.sub(r'ह्(?=[कखपफशषस])', 'ः', t)
    t = re.sub(r'ह्(?=\s|$)', 'ः', t)
    t = t.replace('न्ज', 'ञ्ज').replace('न्च', 'ञ्च').replace('न्ग', 'ङ्ग').replace('न्क', 'ङ्क')
    t = re.sub(r'(?<!उ)च्च', 'च्छ', t)
    t = re.sub(r'मः च', 'ंश्च', t).replace('म्स् त', 'ंस्त').replace('मः त', 'ंस्त')
    t = re.sub(r'(?<=[\u0900-\u097f])म्(?=[कखगघचछजझटठडढतथदधपफबभ])', 'ं', t)   # m before a stop inside a word
    t = re.sub(r'सम्(?=[यरलवशषसह])', 'सं', t)
    t = re.sub(r'([कखगघचछजझटठडढतथदधपफबभ])Jन', 'ज्ञ', t)
    t = ' ' + t + ' '
    # visarga + vowel / voiced consonant
    t = re.sub(r'([क-हळ])ः अ', r'\1ोऽ', t)
    t = re.sub(r'([क-हळ])ः (?=[गघजझडढदधबभनमयरलवह])', r'\1ो ', t)
    t = re.sub(r'([क-हळ])ः (?=[आइईउऊएऐओऔ])', r'\1 ', t)
    t = re.sub(r'ाः (?=[अआइईउऊएऐओऔगघजझडढदधबभनमयरलवह])', 'ा ', t)
    t = re.sub(r'([िुेैोौीू])ः ([अआइईउऊऋएऐओऔ])', lambda m: m.group(1) + 'र' + SIGN[m.group(2)], t)
    t = re.sub(r'([िुेैोौीू])ः (?=[गघजझडढदधबभनमयलवह])', r'\1र्', t)
    # consonant + vowel across the space
    t = re.sub(r'([क-हळ])् ([' + V + '])', lambda m: {'त': 'द', 'क': 'ग', 'ट': 'ड', 'प': 'ब'}.get(m.group(1), m.group(1)) + SIGN[m.group(2)], t)
    # e/o + a -> avagraha
    t = re.sub(r'([ेो]) अ', r'\1ऽ', t)
    # a/aa + vowel
    tab = {'अ': 'ा', 'आ': 'ा', 'इ': 'े', 'ई': 'े', 'उ': 'ो', 'ऊ': 'ो', 'ए': 'ै', 'ऐ': 'ै', 'ओ': 'ौ', 'औ': 'ौ'}
    t = re.sub(r'([क-हळ])(ा?) ([अआइईउऊएऐओऔ])', lambda m: m.group(1) + tab[m.group(3)], t)
    t = re.sub(r'([क-हळ])(ा?) ऋ', lambda m: m.group(1) + 'र्', t)
    t = re.sub(r'ि ([अआउऊएओ])', lambda m: '्य' + SIGN[m.group(1)], t)
    t = re.sub(r'ी ([अआउऊएओ])', lambda m: '्य' + SIGN[m.group(1)], t)
    t = re.sub(r'ु ([अआइईएओ])', lambda m: '्व' + SIGN[m.group(1)], t)
    t = re.sub(r'ि इ', 'ी', t)
    return re.sub(r'\s+', ' ', t).strip()


