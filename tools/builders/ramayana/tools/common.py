STOPS = {}
for nas, row in (('ङ', 'कखगघ'), ('ञ', 'चछजझ'), ('ण', 'टठडढ'), ('न', 'तथदध'), ('म', 'पफबभ')):
    for c in row:
        STOPS[c] = nas


def nasals(line):
    """Word-internal anusvara before a stop -> homorganic nasal (as in the app's Sundarakanda)."""
    return re.sub(r'ं(?=[कखगघचछजझटठडढतथदधपफबभ])', lambda m: STOPS[line[m.end()]] + '्', line)


def clean_line(l):
    l = l.replace('‍', '').replace('‌', '').replace('﻿', '')
    l = l.replace('््', '्')
    l = l.replace('।।', '॥').replace('||', '॥').replace('|', '।')
    l = re.sub(r'[।॥\s]+$', '', l.strip())
    l = re.sub(r'^[।॥\s]+', '', l)
    l = re.sub(r'\s+', ' ', l)
    l = re.sub(r'\s+ऽ', 'ऽ', l)                 # "भरतो ऽपि" -> "भरतोऽपि"
    l = l.replace('ॆ', 'ै') if 'ॆ' in l else l   # legacy-font short e
    l = re.sub(r'र्([यतम])्\1', r'र्\1', l)       # आर्य्य, मुहूर्त्त, धर्म्म -> modern spelling
    l = re.sub(r'\s*।\s*', ' । ', l).strip()     # inner danda spacing (rare)
    return nasals(l)


def fmt(lines):
    """Half-verse per line: ' ।' after each odd line, ' ॥' after the last."""
    out = []
    n = len(lines)
    long_metre = any(count(l) >= 20 for l in lines) or (n == 4 and all(9 <= count(l) <= 13 for l in lines))
    for i, l in enumerate(lines):
        if i == n - 1:
            out.append(l + ' ॥')
        elif long_metre and n == 4 and i % 2 == 0:
            out.append(l)            # pāda lines of a long-metre verse: danda only after 2nd and 4th
        else:
            out.append(l + ' ।')
    return '\n'.join(out)
