/// <reference types="node" />
/**
 * Regenerates src/data/library.generated.ts from the files in src/data/texts.
 * Run: npm run content:index  (also run automatically by `npm run content:check`).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const DIR = resolve(__dirname, '../src/data/texts');
const OUT = resolve(__dirname, '../src/data/library.generated.ts');

const entries: { name: string; file: string }[] = [];
for (const f of readdirSync(DIR).filter((f) => f.endsWith('.ts')).sort()) {
  const src = readFileSync(join(DIR, f), 'utf8');
  for (const m of src.matchAll(/export const (\w+)\s*:\s*Mantra\b/g)) {
    entries.push({ name: m[1], file: f.replace(/\.ts$/, '') });
  }
}

const out = `// AUTO-GENERATED by scripts/gen-index.ts — do not edit by hand.
import type { Mantra } from './types';
${entries.map((e) => `import { ${e.name} } from './texts/${e.file}';`).join('\n')}

export const LIBRARY: Mantra[] = [
${entries.map((e) => `  ${e.name},`).join('\n')}
];
`;
writeFileSync(OUT, out);
console.log(`library.generated.ts: ${entries.length} texts`);
