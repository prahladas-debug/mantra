/// <reference types="node" />
/**
 * Regenerates src/data/library.generated.ts from the files in src/data/texts.
 * Run: npm run content:index  (also run automatically by `npm run content:check`).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const DIR = resolve(__dirname, '../src/data/texts');
const OUT = resolve(__dirname, '../src/data/library.generated.ts');

const entries: { name: string; file: string }[] = [];
for (const f of readdirSync(DIR).filter((f) => f.endsWith('.ts')).sort()) {
  const src = readFileSync(join(DIR, f), 'utf8');
  for (const m of src.matchAll(/export const (\w+)\s*:\s*Mantra\b/g)) {
    entries.push({ name: m[1], file: f.replace(/\.ts$/, '') });
  }
}

const out = `// AUTO-GENERATED by scripts/gen-index.ts — do not edit by hand.
import type { Mantra } from './types';
${[...new Set(entries.map((e) => e.file))]
  .map((f) => `import { ${entries.filter((e) => e.file === f).map((e) => e.name).join(', ')} } from './texts/${f}';`)
  .join('\n')}

export const LIBRARY: Mantra[] = [
${entries.map((e) => `  ${e.name},`).join('\n')}
];
`;
writeFileSync(OUT, out);
console.log(`library.generated.ts: ${entries.length} texts`);

// ---- meaning packs (src/data/meanings/<lang>/*.ts) ----
const MDIR = resolve(__dirname, '../src/data/meanings');
const MOUT = resolve(__dirname, '../src/data/meanings.generated.ts');
const packs: { name: string; path: string }[] = [];
let langs: string[] = [];
try { langs = readdirSync(MDIR).sort(); } catch { langs = []; }
for (const lang of langs) {
  let files: string[] = [];
  try { files = readdirSync(join(MDIR, lang)).filter((f) => f.endsWith('.ts')).sort(); } catch { continue; }
  for (const f of files) {
    const src = readFileSync(join(MDIR, lang, f), 'utf8');
    for (const m of src.matchAll(/export const (\w+)\s*:\s*MeaningPack\b/g)) packs.push({ name: m[1], path: `./meanings/${lang}/${f.replace(/\.ts$/, '')}` });
  }
}
writeFileSync(MOUT, `// AUTO-GENERATED by scripts/gen-index.ts — do not edit by hand.
import type { MeaningPack } from './types';
${packs.map((p) => `import { ${p.name} } from '${p.path}';`).join('\n')}

export const MEANING_PACKS: MeaningPack[] = [${packs.map((p) => p.name).join(', ')}];
`);
console.log(`meanings.generated.ts: ${packs.length} packs`);
